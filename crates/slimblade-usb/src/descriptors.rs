/// Descriptor collection used by the control-request classifier.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DescriptorSet {
    device: [u8; DEVICE_DESCRIPTOR_LENGTH],
}

impl DescriptorSet {
    #[must_use]
    pub const fn new(release_bcd: u16) -> Self {
        Self {
            device: device_descriptor(release_bcd),
        }
    }

    #[must_use]
    pub const fn get(
        &self,
        kind: DescriptorKind,
        descriptor_index: u8,
        index: u16,
    ) -> Option<&[u8]> {
        match (kind, descriptor_index, index) {
            (DescriptorKind::Device, 0, 0) => Some(&self.device),
            (DescriptorKind::Configuration, 0, 0) => Some(&CONFIGURATION_DESCRIPTOR),
            (DescriptorKind::String, 0, 0) => Some(&LANGUAGE_STRING_DESCRIPTOR),
            (DescriptorKind::String, 1 | 2, 0x0409) => Some(&DEVICE_NAME_STRING_DESCRIPTOR),
            (DescriptorKind::Hid, 0, 0) => Some(&MOUSE_HID_DESCRIPTOR),
            (DescriptorKind::Hid, 0, 1) => Some(&VENDOR_HID_DESCRIPTOR),
            (DescriptorKind::Report, 0, 0) => Some(&MOUSE_REPORT_DESCRIPTOR),
            (DescriptorKind::Report, 0, 1) => Some(&VENDOR_REPORT_DESCRIPTOR),
            _ => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{
        CONFIGURATION_DESCRIPTOR, DEVICE_NAME_STRING_DESCRIPTOR, DescriptorSet,
        MOUSE_REPORT_DESCRIPTOR, VENDOR_REPORT_DESCRIPTOR, device_descriptor,
    };
    use crate::DescriptorKind;
    use sha2::{Digest, Sha256};

    fn sha256(chunks: &[&[u8]]) -> [u8; 32] {
        let mut hasher = Sha256::new();
        for chunk in chunks {
            hasher.update(chunk);
        }
        hasher.finalize().into()
    }

    #[test]
    fn live_v453_device_and_configuration_descriptors_match_sysfs() {
        assert_eq!(
            sha256(&[&device_descriptor(0x0453), &CONFIGURATION_DESCRIPTOR]),
            [
                0x91, 0x91, 0x8d, 0x3d, 0x08, 0xae, 0x49, 0x58, 0x08, 0x0a, 0x78, 0xfe, 0x2c, 0x7d,
                0x83, 0xff, 0x58, 0x20, 0x4a, 0xe4, 0xfc, 0x61, 0xfb, 0x48, 0xc0, 0x17, 0x99, 0xd9,
                0x48, 0x36, 0x53, 0xff,
            ]
        );
    }

    #[test]
    fn report_descriptors_match_live_sysfs_hashes() {
        assert_eq!(
            sha256(&[&MOUSE_REPORT_DESCRIPTOR]),
            [
                0x57, 0xba, 0x4a, 0x24, 0xf9, 0x85, 0xa8, 0x06, 0x13, 0x2a, 0x04, 0xfe, 0xa0, 0x6b,
                0xec, 0x30, 0x26, 0xcb, 0x69, 0xb1, 0x2c, 0x95, 0x7a, 0x17, 0x37, 0xa6, 0x45, 0x07,
                0x14, 0x8f, 0xa9, 0x68,
            ]
        );
        assert_eq!(
            sha256(&[&VENDOR_REPORT_DESCRIPTOR]),
            [
                0xa8, 0xbc, 0x6d, 0x8d, 0xe4, 0xd8, 0xc0, 0x67, 0x4e, 0x7d, 0xb3, 0xe2, 0xd2, 0x38,
                0xa2, 0x60, 0x60, 0x2f, 0xc9, 0x49, 0x9a, 0x63, 0x4e, 0x4d, 0x1b, 0xbd, 0x41, 0x80,
                0x91, 0xbf, 0xc5, 0xc6,
            ]
        );
    }

    #[test]
    fn descriptor_lookup_rejects_unknown_indices_and_languages() {
        let descriptors = DescriptorSet::new(0x0454);

        assert_eq!(
            descriptors.get(DescriptorKind::String, 1, 0x0409),
            Some(DEVICE_NAME_STRING_DESCRIPTOR.as_slice())
        );
        assert_eq!(descriptors.get(DescriptorKind::String, 1, 0), None);
        assert_eq!(descriptors.get(DescriptorKind::Report, 0, 2), None);
        assert_eq!(descriptors.get(DescriptorKind::Device, 1, 0), None);
    }
}
